import { describe, expect, it } from "vite-plus/test"

import english from "~/messages/en-US/pages.landing.json"
import italian from "~/messages/it-IT/pages.landing.json"
import { messageFormatProblems, messageProblems } from "~/scripts/check-message-formats"

const COVERAGE_EVIDENCE = "coverage/coverage-summary.json, generated by bun run test:coverage"
const AUTH_EVIDENCE = "src/integrations/better-auth, your database, no metered vendor"

describe("check-message-formats", () => {
  it("finds no problem in any message of any locale", () => {
    expect(messageFormatProblems()).toEqual([])
  })

  it.each([
    {
      changed: ["coverage/coverage-summary.json"],
      locale: "de-DE",
      original: COVERAGE_EVIDENCE,
      value: "Abdeckung/zusammenfassung.json, generiert durch bun run test:coverage",
    },
    {
      changed: ["coverage/coverage-summary.json", "bun run test:coverage"],
      locale: "it-IT",
      original: COVERAGE_EVIDENCE,
      value: "copertura/copertura-riepilogo.json, generato da bun run test:copertura",
    },
    {
      changed: ["bun run test:coverage"],
      locale: "ja-JP",
      original: COVERAGE_EVIDENCE,
      value: "coverage/coverage-summary.json、bun run テストによって生成されたカバレッジサマリーです",
    },
    {
      changed: ["src/integrations/better-auth"],
      locale: "fr-FR",
      original: AUTH_EVIDENCE,
      value: "src/intégrations/better-auth, votre base de données, aucun fournisseur mesuré",
    },
    {
      changed: ["src/integrations/better-auth"],
      locale: "pt-BR",
      original: AUTH_EVIDENCE,
      value: "src/integrações/better-auth, seu banco de dados, sem provedor com cobrança por uso",
    },
  ] as const)("fails the $locale landing evidence that translated a path or a command", ({ changed, locale, original, value }) => {
    expect(messageProblems({ locale, original, value })).toEqual(changed.map((code) => `changed the path or command ${code}`))
  })

  it("passes the evidence once its paths and commands are ICU arguments", () => {
    expect(
      messageProblems({ locale: "it-IT", original: english.record.items.coverage.evidence, value: italian.record.items.coverage.evidence }),
    ).toEqual([])
  })

  it("fails Markdown backticks in a translation of plain text", () => {
    expect(messageProblems({ locale: "es-ES", original: "Real browsers, not jsdom", value: "Navegadores reales, no `jsdom`" })).toEqual([
      "unexpected Markdown code",
    ])
  })
})
